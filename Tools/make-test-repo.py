#!/usr/bin/env python3
"""Build the local APK repository the G5 tests use.

`apk update` is the gate this project dies or survives on, and it has to run
without a network: a repo served from a directory inside the guest root is
the smallest thing that still exercises the whole index path (fetch, tar,
parse, cache, write).

An .apk is a concatenation of gzip streams: an optional signature, then the
control member (.PKGINFO), then the data member.  With --allow-untrusted the
signature is skipped, so each package here is exactly two streams.

    python Tools/make-test-repo.py

writes v2/tests/guest/root/repo/main/aarch64/{APKINDEX.tar.gz,*.apk} plus the
/etc/apk and /var scaffolding apk expects to find.
"""
import base64
import gzip
import hashlib
import io
import os
import sys
import tarfile
import time

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                    "v2", "tests", "guest", "root")
REPO = os.path.join(ROOT, "repo", "main", "aarch64")

PACKAGES = [
    {
        "name": "hello-data",
        "version": "1.0-r0",
        "description": "fixture data for the v2 guest",
        "depends": "",
        "files": {"usr/share/hello/data.txt": b"hello from an apk package\n"},
    },
    {
        "name": "hello-tool",
        "version": "1.0-r0",
        "description": "fixture tool that needs hello-data",
        "depends": "hello-data",
        "files": {
            "usr/bin/hello-tool": b"#!/bin/sh\necho hello-tool\n",
        },
    },
]


def tar_gz(entries):
    """entries: [(name, bytes or None for a directory, mode)]"""
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w") as tar:
        for name, data, mode in entries:
            info = tarfile.TarInfo(name)
            info.mode = mode
            info.uid = info.gid = 0
            info.uname = info.gname = "root"
            info.mtime = 1700000000
            if data is None:
                info.type = tarfile.DIRTYPE
                tar.addfile(info)
            else:
                info.size = len(data)
                tar.addfile(info, io.BytesIO(data))
    return gzip.compress(raw.getvalue(), mtime=0)


def build_package(spec):
    pkginfo = (
        "# Generated by make-test-repo.py\n"
        f"pkgname = {spec['name']}\n"
        f"pkgver = {spec['version']}\n"
        "pkgdesc = %s\n"
        "url = https://example.invalid/\n"
        "builddate = 1700000000\n"
        "packager = v2 test\n"
        "size = %d\n"
        "arch = aarch64\n"
        "origin = %s\n"
        "license = MIT\n"
        "%s"
    )
    total = sum(len(data) for data in spec["files"].values())
    depends = f"depend = {spec['depends']}\n" if spec["depends"] else ""
    control = tar_gz(
        [(".PKGINFO", (pkginfo % (spec["description"], total, spec["name"],
                                  depends)).encode(), 0o644)]
    )

    entries = []
    for path, data in sorted(spec["files"].items()):
        parts = path.split("/")
        for index in range(1, len(parts)):
            directory = "/".join(parts[:index])
            if not any(name == directory for name, _, _ in entries):
                entries.append((directory, None, 0o755))
        entries.append((path, data, 0o755 if path.startswith("usr/bin") else 0o644))
    data = tar_gz(entries)

    return control + data, control, total


def main():
    os.makedirs(REPO, exist_ok=True)
    records = []

    for spec in PACKAGES:
        package, control, installed = build_package(spec)
        name = f"{spec['name']}-{spec['version']}.apk"
        with open(os.path.join(REPO, name), "wb") as handle:
            handle.write(package)
        digest = base64.b64encode(hashlib.sha1(control).digest()).decode()
        record = [
            f"C:Q1{digest}",
            f"P:{spec['name']}",
            f"V:{spec['version']}",
            "A:aarch64",
            f"S:{len(package)}",
            f"I:{installed}",
            f"T:{spec['description']}",
            "U:https://example.invalid/",
            "L:MIT",
            f"o:{spec['name']}",
            "m:v2 test",
            "t:1700000000",
            "c:0000000000000000000000000000000000000000",
        ]
        if spec["depends"]:
            record.append(f"D:{spec['depends']}")
        for path in sorted(spec["files"]):
            record.append(f"p:{path}")
        records.append("\n".join(record))

    index = "\n\n".join(records) + "\n\n"
    index_tar = tar_gz([
        ("DESCRIPTION", b"v2 test repository\n", 0o644),
        ("APKINDEX", index.encode(), 0o644),
    ])
    with open(os.path.join(REPO, "APKINDEX.tar.gz"), "wb") as handle:
        handle.write(index_tar)

    # --- what apk expects around the repo -------------------------------
    # apk 2.x keeps its database in /lib/apk/db (not /var/lib/apk) and needs
    # the directory to exist.  Git cannot store an empty directory, so each
    # one carries a .keep: apk only looks for APKINDEX*/installed/lock there
    # and ignores everything else.
    etc_apk = os.path.join(ROOT, "etc", "apk")
    for directory in (etc_apk,
                      os.path.join(etc_apk, "keys"),
                      os.path.join(ROOT, "var", "cache", "apk"),
                      os.path.join(ROOT, "lib", "apk", "db")):
        os.makedirs(directory, exist_ok=True)
        keep = os.path.join(directory, ".keep")
        if not os.path.exists(keep):
            open(keep, "w").close()
    with open(os.path.join(etc_apk, "repositories"), "w") as handle:
        handle.write("/repo/main\n")
    with open(os.path.join(etc_apk, "arch"), "w") as handle:
        handle.write("aarch64\n")
    for name in ("world",):
        path = os.path.join(etc_apk, name)
        open(path, "w").close()

    print(f"{REPO}")
    for record in records:
        print("  " + record.splitlines()[1])
    print(f"  APKINDEX.tar.gz {len(index_tar)} bytes, "
          f"{len(index)} bytes of index")
    return 0


if __name__ == "__main__":
    sys.exit(main())
